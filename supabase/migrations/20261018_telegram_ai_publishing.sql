-- Telegram scholarship publishing assistant.
-- Additive only: creates new private workflow tables and atomic state transitions.
-- It intentionally does not alter or reference the existing scholarships/admin tables.

BEGIN;

CREATE TABLE public.telegram_scholarship_posts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Stored as text to avoid assuming the existing scholarships.id type or FK behavior.
    scholarship_id text NOT NULL UNIQUE,
    source_version text NOT NULL,
    draft_text text,
    status text NOT NULL DEFAULT 'generating'
        CHECK (status IN (
            'generating', 'draft', 'approved', 'rejected', 'publishing',
            'published', 'publish_unknown', 'stale', 'failed'
        )),
    generation integer NOT NULL DEFAULT 1 CHECK (generation > 0),
    approval_token_hash text UNIQUE,
    approval_token_expires_at timestamptz,
    approved_by_telegram_user_id text,
    approved_at timestamptz,
    review_chat_id text,
    review_message_id bigint,
    channel_chat_id text,
    channel_message_id bigint,
    publish_attempted_at timestamptz,
    published_at timestamptz,
    last_error text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT telegram_post_published_has_message CHECK (
        status <> 'published' OR
        (published_at IS NOT NULL AND channel_chat_id IS NOT NULL AND channel_message_id IS NOT NULL)
    ),
    CONSTRAINT telegram_post_publishing_has_attempt CHECK (
        status <> 'publishing' OR publish_attempted_at IS NOT NULL
    ),
    CONSTRAINT telegram_post_channel_message_unique UNIQUE (channel_chat_id, channel_message_id),
    CONSTRAINT telegram_post_token_is_sha256 CHECK (
        approval_token_hash IS NULL OR approval_token_hash ~ '^[0-9a-f]{64}$'
    ),
    CONSTRAINT telegram_post_token_expiry_paired CHECK (
        (approval_token_hash IS NULL) = (approval_token_expires_at IS NULL)
    ),
    CONSTRAINT telegram_post_draft_has_review_data CHECK (
        status <> 'draft' OR
        (draft_text IS NOT NULL AND approval_token_hash IS NOT NULL AND approval_token_expires_at IS NOT NULL)
    )
);

CREATE INDEX telegram_scholarship_posts_status_updated_idx
    ON public.telegram_scholarship_posts (status, updated_at DESC);

CREATE TABLE public.telegram_webhook_updates (
    update_id bigint PRIMARY KEY CHECK (update_id >= 0),
    event_type text NOT NULL,
    status text NOT NULL DEFAULT 'received'
        CHECK (status IN ('received', 'processing', 'processed', 'retryable', 'dead')),
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    received_at timestamptz NOT NULL DEFAULT now(),
    processed_at timestamptz,
    lease_expires_at timestamptz,
    last_error text
);

CREATE INDEX telegram_webhook_updates_status_received_idx
    ON public.telegram_webhook_updates (status, received_at);

-- A Worker must claim an update before it performs side effects. update_id is
-- the idempotency key; only retryable or expired processing claims can re-enter.
CREATE FUNCTION public.claim_telegram_webhook_update(
    p_update_id bigint,
    p_event_type text
) RETURNS boolean
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
    claimed boolean := false;
BEGIN
    INSERT INTO public.telegram_webhook_updates AS current_update (
        update_id, event_type, status, attempts, lease_expires_at
    ) VALUES (
        p_update_id, pg_catalog.left(p_event_type, 80), 'processing', 1,
        pg_catalog.now() + interval '2 minutes'
    )
    ON CONFLICT (update_id) DO UPDATE
       SET status = 'processing',
           attempts = current_update.attempts + 1,
           lease_expires_at = pg_catalog.now() + interval '2 minutes',
           last_error = NULL
     WHERE current_update.status IN ('received', 'retryable')
        OR (current_update.status = 'processing'
            AND current_update.lease_expires_at < pg_catalog.now())
    RETURNING true INTO claimed;

    RETURN COALESCE(claimed, false);
END;
$$;

CREATE FUNCTION public.finish_telegram_webhook_update(
    p_update_id bigint,
    p_result text,
    p_error text DEFAULT NULL
) RETURNS boolean
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    IF p_result IS NULL OR p_result NOT IN ('processed', 'retryable', 'dead') THEN
        RETURN false;
    END IF;

    UPDATE public.telegram_webhook_updates
       SET status = p_result,
           processed_at = CASE WHEN p_result = 'processed' THEN pg_catalog.now() ELSE NULL END,
           lease_expires_at = NULL,
           last_error = CASE WHEN p_result = 'processed' THEN NULL ELSE pg_catalog.left(p_error, 1000) END
     WHERE update_id = p_update_id
       AND status = 'processing';
    RETURN FOUND;
END;
$$;

-- No policies are created: browser roles have no access to these internal tables.
ALTER TABLE public.telegram_scholarship_posts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.telegram_webhook_updates ENABLE ROW LEVEL SECURITY;

REVOKE ALL PRIVILEGES ON TABLE public.telegram_scholarship_posts
    FROM PUBLIC, anon, authenticated;
REVOKE ALL PRIVILEGES ON TABLE public.telegram_webhook_updates
    FROM PUBLIC, anon, authenticated;

-- The Worker uses a server-only Supabase secret key and performs authorization
-- before invoking these operations. Its key must never be shipped to the browser.
GRANT SELECT, INSERT, UPDATE ON TABLE public.telegram_scholarship_posts TO service_role;
GRANT SELECT, INSERT, UPDATE ON TABLE public.telegram_webhook_updates TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.telegram_scholarship_posts_id_seq TO service_role;

CREATE FUNCTION public.approve_telegram_scholarship_post(
    p_post_id bigint,
    p_current_source_version text,
    p_token_hash text,
    p_telegram_user_id text
) RETURNS boolean
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    UPDATE public.telegram_scholarship_posts
       SET status = 'approved',
           approved_by_telegram_user_id = p_telegram_user_id,
           approved_at = pg_catalog.now(),
           approval_token_hash = NULL,
           approval_token_expires_at = NULL,
           updated_at = pg_catalog.now(),
           last_error = NULL
     WHERE id = p_post_id
       AND status = 'draft'
       AND source_version = p_current_source_version
       AND approval_token_hash = p_token_hash
       AND approval_token_expires_at > pg_catalog.now()
       AND p_token_hash ~ '^[0-9a-f]{64}$'
       AND p_telegram_user_id IS NOT NULL
       AND p_telegram_user_id <> '';
    RETURN FOUND;
END;
$$;

CREATE FUNCTION public.reject_telegram_scholarship_post(
    p_post_id bigint,
    p_current_source_version text,
    p_token_hash text,
    p_telegram_user_id text
) RETURNS boolean
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    UPDATE public.telegram_scholarship_posts
       SET status = 'rejected',
           approved_by_telegram_user_id = p_telegram_user_id,
           approval_token_hash = NULL,
           approval_token_expires_at = NULL,
           updated_at = pg_catalog.now()
     WHERE id = p_post_id
       AND status = 'draft'
       AND source_version = p_current_source_version
       AND approval_token_hash = p_token_hash
       AND approval_token_expires_at > pg_catalog.now()
       AND p_token_hash ~ '^[0-9a-f]{64}$'
       AND p_telegram_user_id IS NOT NULL
       AND p_telegram_user_id <> '';
    RETURN FOUND;
END;
$$;

-- Only one caller can claim an approved post. A later retry cannot claim it again.
CREATE FUNCTION public.claim_telegram_scholarship_publication(
    p_post_id bigint,
    p_current_source_version text
) RETURNS boolean
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    UPDATE public.telegram_scholarship_posts
       SET status = 'publishing',
           publish_attempted_at = pg_catalog.now(),
           updated_at = pg_catalog.now(),
           last_error = NULL
     WHERE id = p_post_id
       AND status = 'approved'
       AND source_version = p_current_source_version;
    RETURN FOUND;
END;
$$;

CREATE FUNCTION public.mark_telegram_scholarship_published(
    p_post_id bigint,
    p_channel_chat_id text,
    p_channel_message_id bigint
) RETURNS boolean
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    UPDATE public.telegram_scholarship_posts
       SET status = 'published',
           channel_chat_id = p_channel_chat_id,
           channel_message_id = p_channel_message_id,
           published_at = pg_catalog.now(),
           updated_at = pg_catalog.now(),
           last_error = NULL
     WHERE id = p_post_id
       AND status = 'publishing'
       AND p_channel_chat_id IS NOT NULL
       AND p_channel_message_id IS NOT NULL;
    RETURN FOUND;
END;
$$;

-- Do not automatically retry an ambiguous Telegram send; reconcile manually first.
CREATE FUNCTION public.mark_telegram_scholarship_publish_unknown(
    p_post_id bigint,
    p_error text
) RETURNS boolean
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    UPDATE public.telegram_scholarship_posts
       SET status = 'publish_unknown',
           last_error = pg_catalog.left(p_error, 1000),
           updated_at = pg_catalog.now()
     WHERE id = p_post_id
       AND status = 'publishing';
    RETURN FOUND;
END;
$$;

-- A definite Telegram rejection is terminal too; retries require a fresh,
-- explicit operator action instead of silently resending a potentially accepted post.
CREATE FUNCTION public.fail_telegram_scholarship_publication(
    p_post_id bigint,
    p_error text
) RETURNS boolean
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    UPDATE public.telegram_scholarship_posts
       SET status = 'failed',
           last_error = pg_catalog.left(p_error, 1000),
           updated_at = pg_catalog.now()
     WHERE id = p_post_id
       AND status = 'publishing';
    RETURN FOUND;
END;
$$;

